async function seedDatabase() {
  console.log('🌱 Starting Firestore seed...\n');
  console.log(`   Project: ${firebaseConfig.projectId}`);
  console.log(`   Restaurant: ${RESTAURANT_NAME}`);
  console.log(`   Items to add: ${sampleMenuItems.length}\n`);

  let added = 0;

  for (const item of sampleMenuItems) {
    try {
      const docRef = await addDoc(collection(db, 'menu_items'), item);
      console.log(`   ✅ Added "${item.name}" (${docRef.id})`);
      added++;
    } catch (error) {
      console.error(`   ❌ Failed to add "${item.name}":`, error.message);
    }
  }

  console.log(`\n🎉 Done! Added ${added}/${sampleMenuItems.length} menu items.`);
  console.log('   You can now refresh your app at http://localhost:3002');
  process.exit(0);
}

seedDatabase();
